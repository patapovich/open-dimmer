#!/usr/bin/env python3
"""Generate src/curves.h: dimming curves as 33-point tables, level 0..1000 ->
conduction time of the half cycle in 1/10000 (trailing edge, from the zero cross).

    0 linear        conduction = level (the stock firmware)
    1 led           CIE 1931 lightness on the conduction time. Dimmable LED lamps
                    mostly turn conduction time into LED current, so this gives
                    even perceived steps.
    2 led_soft      gamma 1.6 on the conduction time, for lamps that already
                    shape it themselves
    3 incandescent  CIE lightness on lamp power: the power of a sine conducted
                    from 0 to angle t is (t - sin t cos t) / pi of the full
                    power; invert that.

Run: python3 tools/gen_curves.py > src/curves.h
"""
import math

POINTS = 33                 # level 0, 31.25, ... 1000
OUT_MAX = 10000

def cie(level):             # perceived lightness L* = level/10 -> relative luminance
    L = level / 10.0
    return L / 903.3 if L <= 8 else ((L + 16) / 116.0) ** 3

def power_fraction(x):      # conduction fraction x of the half cycle -> power fraction
    t = math.pi * x
    return (t - math.sin(t) * math.cos(t)) / math.pi

def conduction_for_power(p):
    lo, hi = 0.0, 1.0
    for _ in range(60):
        mid = (lo + hi) / 2
        if power_fraction(mid) < p:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2

CURVES = [
    ("linear", lambda lv: lv / 1000.0),
    ("led", cie),
    ("led_soft", lambda lv: (lv / 1000.0) ** 1.6),
    ("incandescent", lambda lv: conduction_for_power(cie(lv))),
]

def table(fn):
    out = []
    for i in range(POINTS):
        lv = 1000.0 * i / (POINTS - 1)
        out.append(max(0, min(OUT_MAX, round(fn(lv) * OUT_MAX))))
    out[0] = 0
    out[-1] = OUT_MAX
    return out

print("/* Generated by tools/gen_curves.py, do not edit. */")
print("#ifndef CURVES_H\n#define CURVES_H\n\n#include <stdint.h>\n")
print(f"#define CURVE_POINTS   {POINTS}\n#define CURVE_OUT_MAX  {OUT_MAX}\n#define CURVE_COUNT    {len(CURVES)}\n")
for i, (name, _) in enumerate(CURVES):
    print(f"#define CURVE_{name.upper():13} {i}")
print("\nstatic const uint16_t k_curves[CURVE_COUNT][CURVE_POINTS] = {")
for name, fn in CURVES:
    vals = table(fn)
    print(f"    /* {name} */")
    for j in range(0, POINTS, 11):
        print("    " + ("{ " if j == 0 else "  ") + ", ".join(f"{v:5d}" for v in vals[j:j + 11]) + (" }," if j + 11 >= POINTS else ","))
print("};\n\n#endif")
