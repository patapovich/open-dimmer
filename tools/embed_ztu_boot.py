#!/usr/bin/env python3
"""Write the PY32 bootloader (sector 0) as a C array for the Zigbee module firmware
(tuya-zigbee-switch fork, src/zigbee/secondary_mcu_boot.c), which carries it so that its
SWD master (src/zigbee/mcu_flasher.c) can write it over SWD: job update_bootloader.

    embed_ztu_boot.py build-boot/boot.bin ~/projects/tzs-diag/src/zigbee/secondary_mcu_boot.c

Only a bootloader the module may write (docs/BOOTLOADER.md): a boot_id at 0x10 with the magic
"ODBL" and version 2 or later, at most 4096 bytes (sector 0), the initial SP 0x20000BE0, an
odd reset vector inside the image. The CRC the module checks after writing is the zlib CRC-32
of the whole 4 KB sector (the image padded with 0xFF), the value Open Dimmer reports as DP 136.
Every check is a sys.exit, so python3 -O cannot skip one.
"""
import struct
import sys
import zlib

SECTOR = 4096
SP = 0x20000BE0
FLASH = 0x08000000


def check(img: bytes) -> tuple[int, int, int]:
    """(version, features, sector CRC) of a bootloader the module may carry."""
    if not 0x20 <= len(img) <= SECTOR:
        sys.exit(f"refusing the image: {len(img)} bytes (0x20..{SECTOR})")
    sp, reset = struct.unpack_from("<II", img, 0)
    magic, version, features = struct.unpack_from("<4sBB", img, 0x10)
    if magic != b"ODBL":
        sys.exit("refusing the image: no boot_id (\"ODBL\" at 0x10): v1 or not a bootloader")
    if version < 2:
        sys.exit(f"refusing boot_id version {version}: the SWD master writes v2 and later")
    if sp != SP:
        sys.exit(f"refusing the image: initial SP 0x{sp:08X}, want 0x{SP:08X}")
    if not reset & 1 or not FLASH <= reset & ~1 < FLASH + len(img):
        sys.exit(f"refusing the image: reset vector 0x{reset:08X} not odd inside the image")
    crc = zlib.crc32(img + b"\xFF" * (SECTOR - len(img))) & 0xFFFFFFFF
    return version, features, crc


def main() -> int:
    if len(sys.argv) != 3:
        sys.exit(__doc__.split("\n\n")[1])
    img = open(sys.argv[1], "rb").read()
    version, features, crc = check(img)
    rows = [", ".join(f"0x{b:02x}" for b in img[i:i + 16]) for i in range(0, len(img), 16)]
    body = ",\n    ".join(rows)
    out = f"""/* Generated by open-dimmer tools/embed_ztu_boot.py, do not edit.
 * PY32 bootloader (sector 0) of the AVATTO ZDMS16-2 own MCU firmware: boot_id
 * version {version}, features 0x{features:02X}, {len(img)} bytes; CRC-32 of the 4 KB
 * sector padded with 0xFF: {crc:08x}. Written by the SWD master (mcu_flasher.c)
 * in boards whose device_db entry has secondary_mcu_image (SECONDARY_MCU_IMAGE). */
#include "zigbee/secondary_mcu_boot.h"

#ifdef SECONDARY_MCU_IMAGE
const uint8_t  secondary_mcu_boot[] = {{
    {body}
}};
const uint16_t secondary_mcu_boot_size    = {len(img)};
const uint32_t secondary_mcu_boot_crc     = 0x{crc:08X}u;
const uint8_t  secondary_mcu_boot_version = {version};
#endif
"""
    open(sys.argv[2], "w").write(out)
    print(f"{sys.argv[2]}: bootloader v{version}, {len(img)} bytes, sector CRC {crc:08X}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
