#!/usr/bin/env python3
"""Write the PY32 app image as a C array for the Zigbee module firmware
(tuya-zigbee-switch fork, src/zigbee/secondary_mcu_image.c), which carries it
and updates the MCU with it (tuya_mcu_ota.c).

    embed_ztu.py build/zdms16_py32.img ~/projects/tzs-diag/src/zigbee/secondary_mcu_image.c

Only an image the phase-3 ZTU's image_info takes and the bootloader would install
(docs/BOOTLOADER.md sections 2, 10 and 11): a finished image (magic, size, CRC), no
bench flag (SIM, MEASURE, DIAG), SP 0x20000BE0, an odd reset vector inside the image,
at most 14 KB and over 12 KB only with RING_HIGH, a build 256..0xFFFD with CONFIRMS
(no build 0: a 2.1.x app is not carried).
Every check is a sys.exit, so python3 -O cannot skip one.
"""
import os
import sys

sys.dont_write_bytecode = True                         # no __pycache__ in tools/
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fwimage as fw                                   # noqa: E402


def check(img):
    """Header of an image the module may carry; sys.exit with the reason otherwise."""
    try:
        h = fw.finished(img)
    except fw.Refused as e:
        sys.exit(f"refusing the image: {e}")
    if h.flags & fw.FLAG_SIM or h.version == fw.VERSION_SIM:
        sys.exit("refusing a SIM bench build: the module would push it to dimmers on the mains")
    if h.flags & fw.FLAG_MEASURE:
        sys.exit("refusing a measurement build: its outputs are always off")
    if h.flags & fw.FLAG_DIAG:
        sys.exit("refusing a diagnostics build: it takes no update, so it would stay on every MCU")
    if h.version == fw.VERSION_NEVER:
        sys.exit("refusing version 0xFF: no update could ever be offered to an MCU that has it")
    if h.flags & fw.FLAGS_RESERVED:
        sys.exit(f"refusing flags 0x{h.flags:02X}: 0x20..0x80 are reserved")
    p = fw.version_problem(h.version, h.flags)
    if p:
        sys.exit(f"refusing the image: {p}")
    p = fw.layout_problem(h.size, h.flags) or fw.vector_problem(img, h.size, exact_sp=True)
    if p:
        sys.exit(f"refusing the image: {p}")
    if h.build == fw.BUILD_NONE:
        sys.exit("refusing an image without a build number (2.1.x): no unit runs one under the v2 bootloader")
    if h.build == fw.BUILD_SIM:
        sys.exit("refusing build 0xFFFE: SIM builds only")
    p = fw.build_problem(h.build, h.flags)
    if p:
        sys.exit(f"refusing the image: {p}")
    return h


def c_file(img, h):
    v = fw.version_str(h.version)
    lines = [", ".join(f"0x{b:02x}" for b in img[i:i + 16]) for i in range(0, len(img), 16)]
    body = ",\n    ".join(lines)
    # py32-bump (fork workflow) reads the version from the first comment line: keep its format.
    return f"""/* Generated by zdms16-py32 fw/tools/embed_ztu.py, do not edit.
 * PY32 app image of the AVATTO ZDMS16-2 own MCU firmware: version {v}
 * (0x{h.version:02X}), {h.size} bytes, CRC-32 {h.crc:08x}. Built into boards whose
 * device_db entry has secondary_mcu_image (SECONDARY_MCU_IMAGE).
 * Image build: {h.build}; header flags 0x{h.flags:02X}. */
#include "zigbee/secondary_mcu_image.h"

#ifdef SECONDARY_MCU_IMAGE
const uint8_t  secondary_mcu_image[] = {{
    {body}
}};
const uint32_t secondary_mcu_image_size = sizeof(secondary_mcu_image);
#else
const uint8_t  secondary_mcu_image[1]   = {{ 0 }};
const uint32_t secondary_mcu_image_size = 0;
#endif
"""


def main(argv):
    args = argv[1:]
    for a in args:
        if a.startswith("--"):
            sys.exit(f"unknown option {a}\n{__doc__}")
    if len(args) != 2:
        sys.exit(__doc__)
    with open(args[0], "rb") as f:
        img = f.read()
    h = check(img)
    text = c_file(img, h)
    with open(args[1], "w") as f:
        f.write(text)
    print(f"{args[1]}: version {fw.version_str(h.version)}, build {h.build}, {h.size} bytes, crc {h.crc:08x}")


if __name__ == "__main__":
    main(sys.argv)
